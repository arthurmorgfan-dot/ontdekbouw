/** Pre-sized local WebP scenes: no runtime image service or external image requests. */
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const sources = [
  ...['loop', 'grow', 'hive', 'rise', 'mend', 'clarke'].map(name => `/images/projects/${name}-hero.png`),
  ...['river-civilization', 'food', 'movement'].map(name => `/images/future/${name}.webp`),
];
const manifest = {};
await mkdir(resolve(root, 'public/images/scenes'), { recursive: true });
for (const src of sources) {
  const input = resolve(root, 'public' + src);
  const { width, height } = await sharp(input).metadata();
  const key = src.split('/').at(-1).replace(/\.(png|webp)$/, '');
  const variants = [];
  // Preserve the source resolution; no expensive enlargement for large desktops.
  for (const size of [...new Set([480, 800, 1200, Math.min(width, 1600)].filter(size => size <= width))].sort((a,b) => a-b)) {
    const url = `/images/scenes/${key}-${size}.webp`;
    const output = await sharp(input).resize({ width: size }).webp({ quality: 80 }).toFile(resolve(root, 'public' + url));
    variants.push({ src: url, width: output.width });
  }
  manifest[src] = { width, height, variants };
}
await writeFile(resolve(root, 'src/lib/scene-images.ts'), `// Generated by scripts/build-scene-images.mjs.\nexport const sceneImages: Record<string, { width: number; height: number; variants: { src: string; width: number }[] }> = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Prepared ${sources.length} scenes with exact responsive widths.`);
